def lang() -> str:
    try:
        return app.storage.user.get("lang", "en")
    except Exception:  # noqa: BLE001 - outside a request context
        return "en"


def t(key: str, **fmt: Any) -> str:
    entry = T.get(key)
    if entry is None:
        return key
    text = entry.get(lang(), entry["en"])
    return text.format(**fmt) if fmt else text


def L(obj: dict[str, str] | None) -> str:
    """Pick the current language from an {'en': ..., 'hi': ...} object."""
    if not obj:
        return ""
    return obj.get(lang()) or obj.get("en", "")


def error_text(code: str, detail: dict[str, Any] | None = None) -> str:
    detail = detail or {}
    key = f"err_{code}"
    if key not in T:
        key = "err_error"
    try:
        msg = t(key, **{k: v for k, v in detail.items() if isinstance(v, (int, str))})
    except (KeyError, IndexError):
        msg = t(key)
    if code == "weak_password" and detail.get("problems"):
        need = ", ".join(PW_PROBLEMS.get(p, {}).get(lang(), p) for p in detail["problems"])
        msg += (" Needs: " if lang() == "en" else " ज़रूरी: ") + need
    return msg
